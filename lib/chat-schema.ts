import { z } from "zod";
import { insightInputSchema } from "./insight-schema";

const messageSchema = z.object({
  role: z.enum(["user", "assistant"]),
  parts: z.array(z.union([
    z.object({ type: z.literal("text"), text: z.string().max(8000) }),
    z.object({ type: z.literal("step-start") }),
  ])).min(1).max(20),
});
export const chatInputSchema = z.object({
  data: insightInputSchema,
  question: z.string().trim().min(1).max(2000).optional(),
  messages: z.array(messageSchema).min(1).max(40).optional(),
}).refine(value => Boolean(value.question) !== Boolean(value.messages), "Передайте question или messages");

